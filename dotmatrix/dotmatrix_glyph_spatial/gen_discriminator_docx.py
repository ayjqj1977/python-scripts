# ---------------- 3 方法 ----------------
H("三、方法", 1)
P("模型：多类逻辑回归（softmax 判别头）。它是最简单的\"会学习\"的模型——参数由梯度下降（Adam）从数据训出，"
  "对没见过的字也能给出判断，不是查表，也不是死公式。我们刻意不用深度网络：样本不到六千、类别只有十来个，"
  "小模型既够用、又保住可解读性（每个输入维度对每类语义的\"话语权\"就是它的权重，人能直接读）。")
P("特征组装成三种输入，用以隔离\"字形结构化特征\"各自的贡献：")
P("  A. 仅部首 one-hot —— 测\"形旁表义\"最朴素的可解读信号；")
P("  B. 仅几何结构（s32 + det + 笔画数 + 结构类型，不含部首）—— 测抛开部首标签后，纯字形几何能否预测语义；")
P("  C. 全部特征（部首 + 结构 + 笔画数 + s32 + det）—— 性能上限。")
P("训练协议：所有特征统一标准化（零均值单位方差），偏置初始化为类别先验（开局即达基线），加 L2 正则防过拟合；"
  "按\"字\"随机 80/20 划分训练/测试集，测试集是模型训练时从未见过的字，以此检验真·泛化；"
  "每个设置跑 5 个随机种子报告均值±标准差。全程在普通笔记本电脑 CPU 上几秒内完成，不依赖任何云端 GPU——"
  "本地、离线、零训练（指不训云端大模型）的约束在此天然满足。")

