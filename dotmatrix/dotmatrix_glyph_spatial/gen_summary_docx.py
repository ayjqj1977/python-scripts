rpr = style.element.get_or_add_rPr()
rfonts = rpr.get_or_add_rFonts()
rfonts.set(qn('w:eastAsia'), 'Microsoft YaHei')

def cjk(run):
    run.font.name = 'Microsoft YaHei'
    r = run._element
    rp = r.get_or_add_rPr()
    rf = rp.get_or_add_rFonts()
    rf.set(qn('w:eastAsia'), 'Microsoft YaHei')

def H(text, level=1):
    h = doc.add_heading(text, level=level)
    for r in h.runs:
        cjk(r)
    return h

def P(text='', bold=False, italic=False):
    p = doc.add_paragraph()
    run = p.add_run(text)
    run.bold = bold
    run.italic = italic
    cjk(run)
    return p

def B(text):
    p = doc.add_paragraph(style='List Bullet')
    run = p.add_run(text)
    cjk(run)
    return p

def rich(parts):
    """parts: list of (text, bold) tuples"""
    p = doc.add_paragraph()
    for t, b in parts:
        run = p.add_run(t)
        run.bold = b
        cjk(run)
    return p

