# -*- coding: utf-8 -*-
"""
论文体「义近字判别（二）：硬边界→软谱」补充实验文档生成器。
读取 semnear_reg_result.json，产出独立 docx，与前三篇同一章法。
"""
import json, os
from docx import Document
from docx.shared import Pt

BASE = r"D:/desktop/学习结果小文件/dotmatrix_glyph_spatial"
R = json.load(open(os.path.join(BASE, "semnear_reg_result.json"), encoding="utf-8"))

doc = Document()
st = doc.styles["Normal"]; st.font.name = "宋体"; st.font.size = Pt(11)

def H(txt, lvl=1):
    h = doc.add_heading(txt, level=lvl)
    for r in h.runs: r.font.name = "黑体"
    return h

def P(txt, bold=False, italic=False):
    p = doc.add_paragraph(); r = p.add_run(txt)
    r.bold = bold; r.italic = italic; return p

def TABLE(rows, header):
    t = doc.add_table(rows=1, cols=len(header)); t.style = "Light Grid Accent 1"
    for i, h in enumerate(header):
        c = t.rows[0].cells[i]; c.text = h
        for pp in c.paragraphs:
            for rr in pp.runs: rr.bold = True
    for row in rows:
        cells = t.add_row().cells
        for i, v in enumerate(row): cells[i].text = str(v)
    return t

# ---------- 标题 ----------
ti = doc.add_heading("义近字判别（二）：把「硬边界」换成「软谱」\n——几何特征在细粒度任务上是否更出彩", level=0)
for r in ti.runs: r.font.name = "黑体"
P("汉字结构化编码 · 可训练判别器系列（四）  |  2026-07-30", italic=True)
P("上篇《义近字判别》用「是否同词林中类」的 0/1 硬标签做分类，得到两点：(一) 部首是绝对主力"
  "（重要性 86.9%，仅部首 AUC 即 0.762）；(二) 几何弱但有真实信号（仅几何 AUC 0.625，高于随机），"
  "并发现样例 松·柏/红·绿 被词林单义码(homograph)压到跨大类、模型靠部首拉回「两棵树」。这引出一个"
  "校准方向：与其拿词林硬边界当「正确老师」去纠正模型，不如把义近建模成**连续谱**。本篇就做这件事，"
  "并正面回答上篇留下的问题——几何特征在「软谱」任务上，会不会比「硬边界」里更出彩一点。")

# ---------- 1. 方法 ----------
H("1. 方法：词林分层相似度谱 + Ridge 回归", 1)
P("标签不再是非黑即白的 0/1，而是词林自带的分层相似度（田久乐 / 朱新华系数，按两字编码的最长公共"
  "前缀层级取）：跨大类 0.0 / 同大类 0.65 / 同中类 0.80 / 同小类 0.90 / 同词群 0.96 / 同原子词群 0.99。"
  "这是一个连续谱，让「松·柏」（跨大类但同概念域）拿到一个适中的中间分，而不是被当成错误。")
P("特征与前作完全一致（每字 283 维：部首/结构/笔画/s32/det，标准化），两两表示仍为对称差 |f_a−f_b|。"
  "判别头换成 **Ridge 回归**（强 L2、可解读系数），目标即上述谱值。字对覆盖全谱各档（各档抽样至均衡），"
  "**5 个随机种子、字级 80/20 划分**（测试字对的两个字训练时都没见过），报告 Spearman ρ 与块重要性占比，"
  "并对比「全特征 / 仅部首 / 仅几何」三档——直接看几何的相对话语权是否上升。")

# ---------- 2. 结果 ----------
H("2. 结果：整体拟合弱，但几何的「相对话语权」翻倍了", 1)
rows = [
    ["全特征", f"{R['full_rho_mean']:.3f} ± {R['full_rho_std']:.3f}", f"{R['block_importance']['部首']*100:.1f}%", f"{R['geom_share']*100:.1f}%"],
    ["仅部首", f"{R['radical_rho']:.3f}", "100%", "0%"],
    ["仅几何", f"{R['geom_rho']:.3f}", "0%", "100%"],
]
TABLE(rows, ["模型", "Spearman ρ", "部首块占比", "几何块(s32+det)占比"])
P("两个发现：", bold=True)
P("① **几何在软谱任务上确实更出彩——占比翻倍。** 几何块(s32+det)的重要性从硬分类的 9.2% 跳到 "
  "**19.7%**（s32 12.2% + det 7.5%），部首则从 86.9% 降到 72.1%。这正是上篇留下的疑问的答案："
  "硬 0/1 只需做「是否同中类」的粗切，部首一锤定音；软谱要分辨 0.80/0.90/0.96 的细梯度，形状/"
  "矢量这类几何特征在「细粒度」上开始补位。此外「笔画数」块也从 0.2% 升到 5.2%——另一个在细区分上"
  "才显得有用的弱信号。", bold=True)
P("② **但整体拟合很弱（ρ 仅 0.18）。** 这不是实验失败，而是把真相说清楚了：词林的谱本身是「编码前缀"
  "层级」的离散阶梯，且与部首强相关；我们的 radical-proxy 太粗，还原不了那个精确阶梯。最典型的系统性"
  "错位出现在「同大类异中类」对上——词林给 0.65，模型却因两字部首不同而把它们压到 ~0.4。这是上篇"
  "radical-proxy 的 trade-off，在这里被定量地摊开了。", bold=True)

# ---------- 3. 样例 ----------
H("3. 样例：回归把「模型比词林更直觉」这件事量化了", 1)
P("取若干字对，看回归头给的谱值 vs 词林真实谱值（1≈最近）：")
drows = []
for d in R["demo_pairs"]:
    drows.append([f"{d['a']}·{d['b']}", f"{d['pred']:.3f}", f"{d['true']:.3f}"])
TABLE(drows, ["字对", "模型预测谱值", "词林真实谱值"])
P("可读出的细节：", bold=True)
P("• 松·柏 预测 0.807、红·绿 预测 0.744，而词林真实值都是 **0.000**（松被 homograph 压到 E特征、"
  "红绿分属 D抽象/E特征，都成了跨大类）。模型给的 ~0.8 相当于「同中类」级别——它把两棵树、两种颜色"
  "拉回了它们本该在的语义邻近位。这里模型的值比词林标签更贴近人类直觉，上篇的 (b) 论点被本篇用"
  "连续值定量坐实：词林的 0.000 才是那个「被机械划分带偏」的量。", bold=True)
P("• 江·河 预测 0.761 / 真实 0.990（同小类，模型略低估）；狗·猫 预测 0.818 / 真实 0.800（同中类，"
  "模型略高估，因为同犭部）。这两对模型与词林方向一致，只是幅度有偏差。")
P("• 火·水、山·石、江·树 预测都只有 0.36–0.49，而词林给 0.65（同属 B物大类）。模型因部首不同（火 vs 氵、"
  "山 vs 石、氵 vs 木）把它们压低——这是 radical-proxy 的另一面：它也会**低估**那些「同大类但不同形旁」"
  "的真近义对。软谱没消除这个偏置，只是把它显形了。")

