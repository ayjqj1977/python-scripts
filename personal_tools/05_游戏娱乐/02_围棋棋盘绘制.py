# 导入画图工具（不用懂，复制就行）
import turtle

# 1. 初始化：开窗+准备工具+自定义变量（修复setup参数问题）
turtle.setup(800, 700)  # 修复：去掉中文参数名，直接写数值（宽800，高700）
画笔 = turtle.Turtle()  # 创建一支“画笔”
画笔.speed(0)  # 画笔速度最快（0=最快，不用改）
画笔.hideturtle()  # 隐藏画笔的小箭头（只看画的图）

# 自定义变量（全中文，一眼懂）
格子大小 = 30  # 每个小格子的边长（30像素）
棋盘边界 = 9 * 格子大小  # 棋盘边缘位置（9个格子×30=270像素）
当前颜色 = "black"  # 初始落子颜色（黑棋先行）
棋子列表 = []  # 装已落棋子的信息（画笔、颜色、坐标）
按钮文字列表 = []  # 装按钮文字的画笔（方便清空）
已落子位置 = set()  # 记已落子的坐标（避免重复落子）

# 2. 画按钮的函数（单独画按钮，逻辑清晰）
def 画按钮(按钮x, 按钮y, 按钮文字, 按钮颜色):
    # 画按钮背景（矩形）
    按钮画笔 = turtle.Turtle()
    按钮画笔.speed(0)
    按钮画笔.hideturtle()
    按钮画笔.penup()
    按钮画笔.goto(按钮x - 35, 按钮y - 15)  # 按钮左下角位置
    按钮画笔.pendown()
    按钮画笔.color(按钮颜色)
    按钮画笔.begin_fill()
    # 画矩形（循环2次）
    for _ in range(2):
        按钮画笔.forward(70)  # 按钮宽度70像素
        按钮画笔.left(90)
        按钮画笔.forward(30)  # 按钮高度30像素
        按钮画笔.left(90)
    按钮画笔.end_fill()
    
    # 写按钮文字
    文字画笔 = turtle.Turtle()
    文字画笔.speed(0)
    文字画笔.hideturtle()
    文字画笔.penup()
    文字画笔.goto(按钮x, 按钮y - 10)  # 文字居中位置
    文字画笔.color("white")
    文字画笔.write(按钮文字, align="center", font=("SimHei", 10, "bold"))
    按钮文字列表.append(文字画笔)  # 把文字画笔存起来

# 3. 画棋盘的函数（核心：画底色+网格+星位+按钮）
def 画棋盘():
    # 画棋盘木质底色
    画笔.penup()
    画笔.goto(-棋盘边界 - 10, -棋盘边界 - 10 + 50)  # 棋盘下移50像素（给按钮留空间）
    画笔.pendown()
    画笔.color("#E6D8B8")  # 浅棕色（木质底色）
    画笔.begin_fill()
    # 画底色矩形
    for _ in range(2):
        画笔.forward(2*棋盘边界 + 20)  # 底色宽度（2×270+20=560）
        画笔.left(90)
        画笔.forward(2*棋盘边界 + 20)  # 底色高度（560）
        画笔.left(90)
    画笔.end_fill()
    
    # 画网格线（深棕色）
    画笔.color("#8B4513")
    # 画横线（从左到右，每隔30像素一条）
    for y坐标 in range(-棋盘边界, 棋盘边界 + 1, 格子大小):
        画笔.penup()
        画笔.goto(-棋盘边界, y坐标 + 50)  # 下移50像素，匹配棋盘位置
        画笔.pendown()
        画笔.goto(棋盘边界, y坐标 + 50)
    
    # 画竖线（从下到上，每隔30像素一条）
    for x坐标 in range(-棋盘边界, 棋盘边界 + 1, 格子大小):
        画笔.penup()
        画笔.goto(x坐标, -棋盘边界 + 50)
        画笔.pendown()
        画笔.goto(x坐标, 棋盘边界 + 50)
    
    # 画星位（5个关键点，黑色小圆）
    画笔.color("black")
    星位坐标 = [
        (-6*格子大小, -6*格子大小),  # 左下星位
        (6*格子大小, 6*格子大小),    # 右上星位
        (-6*格子大小, 6*格子大小),   # 左上星位
        (6*格子大小, -6*格子大小),   # 右下星位
        (0, 0)                         # 天元（中心）
    ]
    for (x, y) in 星位坐标:
        画笔.penup()
        画笔.goto(x, y + 50)  # 下移50像素
        画笔.pendown()
        画笔.circle(3)  # 星位半径3像素

    # 画右上角的竖排按钮
    画按钮(320, 200, "悔棋", "blue")
    画按钮(320, 140, "清空棋盘", "red")

# 4. 落子功能（鼠标点击棋盘时触发）
def 落子(鼠标x, 鼠标y):
    global 当前颜色  # 声明要修改“当前颜色”这个全局变量
    # 只响应棋盘区域的点击（排除按钮区域）
    if 鼠标x > 棋盘边界 + 10 or 鼠标x < -棋盘边界 -10 or 鼠标y > 棋盘边界 + 60 or 鼠标y < -棋盘边界 + 40:
        return  # 不在棋盘区域，不执行后续操作
    
    # 把鼠标坐标对齐到棋盘格点（四舍五入到30的倍数）
    对齐x = round(鼠标x / 格子大小) * 格子大小
    对齐y = round((鼠标y - 50) / 格子大小) * 格子大小  # 减去50，匹配棋盘下移
    
    # 判断：这个位置是否已经有棋子了
    if (对齐x, 对齐y) in 已落子位置:
        return  # 已有棋子，不允许落子
    
    # 画棋子（圆）
    棋子画笔 = turtle.Turtle()
    棋子画笔.speed(0)
    棋子画笔.hideturtle()
    棋子画笔.penup()
    棋子画笔.goto(对齐x, 对齐y + 50 - 格子大小/2)  # 棋子居中位置
    棋子画笔.color(当前颜色)
    棋子画笔.begin_fill()
    棋子画笔.circle(格子大小/2 - 1)  # 棋子半径（30/2-1=14像素，略小于格子）
    棋子画笔.end_fill()
    
    # 记录棋子信息（方便悔棋）
    棋子列表.append((棋子画笔, 当前颜色, (对齐x, 对齐y)))
    已落子位置.add((对齐x, 对齐y))  # 把坐标加入“已落子位置”集合
    
    # 切换落子颜色（黑→白，白→黑）
    当前颜色 = "white" if 当前颜色 == "black" else "black"

# 5. 悔棋功能（点击“悔棋”按钮时触发）
def 悔棋(鼠标x, 鼠标y):
    # 判断：是否点击了“悔棋”按钮的区域（x：285-355，y：185-215）
    if 285 < 鼠标x < 355 and 185 < 鼠标y < 215 and 棋子列表:
        # 取出最后一颗棋子的信息
        最后棋子, 最后颜色, 最后坐标 = 棋子列表.pop()
        最后棋子.clear()  # 清除这颗棋子
        已落子位置.remove(最后坐标)  # 从“已落子位置”中删除
        global 当前颜色
        当前颜色 = 最后颜色  # 恢复上一轮的落子颜色

# 6. 清空棋盘功能（点击“清空棋盘”按钮时触发）
def 清空棋盘(鼠标x, 鼠标y):
    # 判断：是否点击了“清空棋盘”按钮的区域（x：285-355，y：125-155）
    if 285 < 鼠标x < 355 and 125 < 鼠标y < 155:
        global 棋子列表, 当前颜色, 按钮文字列表, 已落子位置
        # 清除所有棋子
        for 棋子, _, _ in 棋子列表:
            棋子.clear()
        # 清除所有按钮文字
        for 文字画笔 in 按钮文字列表:
            文字画笔.clear()
        # 重置所有变量
        按钮文字列表 = []
        棋子列表 = []
        已落子位置.clear()
        当前颜色 = "black"  # 重置为黑棋先行
        # 重新绘制按钮
        画按钮(320, 200, "悔棋", "blue")
        画按钮(320, 140, "清空棋盘", "red")

# 7. 绑定鼠标点击事件（让按钮和棋盘生效）
画棋盘()  # 先画好棋盘和按钮
turtle.onscreenclick(落子)  # 点击棋盘→落子
turtle.onscreenclick(悔棋, add=True)  # 点击悔棋按钮→悔棋（add=True不覆盖之前的事件）
turtle.onscreenclick(清空棋盘, add=True)  # 点击清空按钮→清空棋盘
turtle.done()  # 保持窗口打开（最后一行必写）
