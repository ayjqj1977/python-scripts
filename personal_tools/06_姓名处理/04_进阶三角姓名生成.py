import turtle
a=turtle.Turtle()
turtle.title("贾庆军的小作品")
turtle.colormode(255)
turtle.bgcolor(0,255,0)
a.begin_fill()
a.speed(5)
a.pensize(10)
a.pencolor(255,0,0)
a.fillcolor(20,30,125) 
a.pendown()
a.forward(200)
a.left(120)
a.forward(200)
a.left(120)
a.forward(200)
a.left(120)
a.forward(200)
a.end_fill()
a.penup()
a.goto(0,350)
a.pendown()
a.pencolor(0,0,0)

a.write("贾庆军的作品")
a.font=("Arial", 20, "bold")
turtle.done()

